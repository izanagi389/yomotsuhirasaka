//! 内部向けのアドレスの判定（13-security.md「外部への送信」、Q95, Q112）。
//!
//! 内部向けには、プライベートアドレス、ループバック、リンクローカル、クラウドのメタデータサーバー、
//! `0.0.0.0`、IPv4を埋め込んだIPv6アドレスなどを含める。迷うものは内部向けとして扱う
//! （送れないほうが、内部に届くよりも安全なため）。

use std::net::{IpAddr, Ipv4Addr, Ipv6Addr};

/// 外部への送信先として使ってはいけないアドレスか。
pub fn is_internal(ip: IpAddr) -> bool {
    match ip {
        IpAddr::V4(v4) => is_internal_v4(v4),
        IpAddr::V6(v6) => is_internal_v6(v6),
    }
}

fn in_v4(ip: Ipv4Addr, net: [u8; 4], prefix: u32) -> bool {
    let mask = if prefix == 0 {
        0
    } else {
        u32::MAX << (32 - prefix)
    };
    (u32::from(ip) & mask) == (u32::from(Ipv4Addr::from(net)) & mask)
}

/// IPv4の、外部への送信に使えない範囲（IANA の特別な用途のアドレスの一覧から、外部に届かないもの）。
const INTERNAL_V4: &[([u8; 4], u32)] = &[
    ([0, 0, 0, 0], 8),       // 「この網」。0.0.0.0 は自分自身に届く
    ([10, 0, 0, 0], 8),      // プライベート
    ([100, 64, 0, 0], 10),   // キャリアグレードNAT
    ([127, 0, 0, 0], 8),     // ループバック
    ([169, 254, 0, 0], 16), // リンクローカル（クラウドのメタデータサーバー 169.254.169.254 を含む）
    ([172, 16, 0, 0], 12),  // プライベート
    ([192, 0, 0, 0], 24),   // IETFのプロトコル用（192.0.0.192 などのメタデータを含む）
    ([192, 0, 2, 0], 24),   // 文書用
    ([192, 88, 99, 0], 24), // 6to4 の中継（廃止）
    ([192, 168, 0, 0], 16), // プライベート
    ([198, 18, 0, 0], 15),  // ベンチマーク用
    ([198, 51, 100, 0], 24), // 文書用
    ([203, 0, 113, 0], 24), // 文書用
    ([224, 0, 0, 0], 4),    // マルチキャスト
    ([240, 0, 0, 0], 4),    // 予約（255.255.255.255 を含む）
];

fn is_internal_v4(ip: Ipv4Addr) -> bool {
    INTERNAL_V4
        .iter()
        .any(|&(net, prefix)| in_v4(ip, net, prefix))
}

fn in_v6(ip: Ipv6Addr, net: [u16; 8], prefix: u32) -> bool {
    let mask = if prefix == 0 {
        0
    } else {
        u128::MAX << (128 - prefix)
    };
    (u128::from(ip) & mask) == (u128::from(Ipv6Addr::from(net)) & mask)
}

/// IPv6の、外部への送信に使えない範囲。IPv4を埋め込む形式は、埋め込んだアドレスによらず使わない。
const INTERNAL_V6: &[([u16; 8], u32)] = &[
    ([0, 0, 0, 0, 0, 0, 0, 0], 96), // 未指定（::）・ループバック（::1）・IPv4互換（::a.b.c.d）
    ([0, 0, 0, 0, 0, 0xffff, 0, 0], 96), // IPv4射影（::ffff:a.b.c.d）
    ([0, 0, 0, 0, 0xffff, 0, 0, 0], 96), // IPv4変換（::ffff:0:a.b.c.d）
    ([0x64, 0xff9b, 0, 0, 0, 0, 0, 0], 96), // NAT64（64:ff9b::a.b.c.d）
    ([0x64, 0xff9b, 1, 0, 0, 0, 0, 0], 48), // 組織内のNAT64
    ([0x100, 0, 0, 0, 0, 0, 0, 0], 64), // 破棄用
    ([0x2001, 0, 0, 0, 0, 0, 0, 0], 32), // Teredo（IPv4を埋め込む）
    ([0x2001, 0x2, 0, 0, 0, 0, 0, 0], 48), // ベンチマーク用
    ([0x2001, 0xdb8, 0, 0, 0, 0, 0, 0], 32), // 文書用
    ([0x2002, 0, 0, 0, 0, 0, 0, 0], 16), // 6to4（IPv4を埋め込む）
    ([0x3fff, 0, 0, 0, 0, 0, 0, 0], 20), // 文書用
    ([0x5f00, 0, 0, 0, 0, 0, 0, 0], 16), // SRv6 の識別子
    ([0xfc00, 0, 0, 0, 0, 0, 0, 0], 7), // ユニークローカル（AWS の fd00:ec2::254 を含む）
    ([0xfe80, 0, 0, 0, 0, 0, 0, 0], 10), // リンクローカル
    ([0xfec0, 0, 0, 0, 0, 0, 0, 0], 10), // サイトローカル（廃止）
    ([0xff00, 0, 0, 0, 0, 0, 0, 0], 8), // マルチキャスト
];

fn is_internal_v6(ip: Ipv6Addr) -> bool {
    INTERNAL_V6
        .iter()
        .any(|&(net, prefix)| in_v6(ip, net, prefix))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn internal(s: &str) -> bool {
        is_internal(s.parse().unwrap())
    }

    #[test]
    fn internal_v4() {
        for a in [
            "0.0.0.0",
            "0.1.2.3",
            "10.0.0.1",
            "100.64.0.1",
            "100.127.255.254",
            "127.0.0.1",
            "127.255.255.255",
            "169.254.169.254",
            "172.16.0.1",
            "172.31.255.255",
            "192.0.0.192",
            "192.0.2.1",
            "192.168.1.1",
            "198.18.0.1",
            "198.19.255.255",
            "224.0.0.1",
            "239.255.255.250",
            "240.0.0.1",
            "255.255.255.255",
        ] {
            assert!(internal(a), "{a} should be internal");
        }
    }

    #[test]
    fn public_v4() {
        for a in [
            "1.1.1.1",
            "8.8.8.8",
            "93.184.215.14",
            "100.63.255.255",
            "100.128.0.0",
            "172.15.255.255",
            "172.32.0.0",
            "192.169.0.1",
            "198.20.0.1",
            "223.255.255.255",
        ] {
            assert!(!internal(a), "{a} should be public");
        }
    }

    #[test]
    fn internal_v6() {
        for a in [
            "::",
            "::1",
            "::127.0.0.1",
            "::8.8.8.8",
            "::ffff:127.0.0.1",
            "::ffff:8.8.8.8",
            "::ffff:0:10.0.0.1",
            "64:ff9b::808:808",
            "64:ff9b:1::1",
            "100::1",
            "2001::1",
            "2001:db8::1",
            "2002:7f00:1::",
            "fc00::1",
            "fd00:ec2::254",
            "fe80::1",
            "fec0::1",
            "ff02::1",
        ] {
            assert!(internal(a), "{a} should be internal");
        }
    }

    #[test]
    fn public_v6() {
        for a in [
            "2606:4700:4700::1111",
            "2a00:1450:4001:80b::200e",
            "2400:cb00::1",
        ] {
            assert!(!internal(a), "{a} should be public");
        }
    }
}
